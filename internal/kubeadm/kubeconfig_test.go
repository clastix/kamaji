func TestCreateKubeconfigIsValidFromIssueTime(t *testing.T) {
	initConfiguration, err := kubeadmconfig.DefaultedStaticInitConfiguration()
	require.NoError(t, err)

	initConfiguration.ControlPlaneEndpoint = "tenant.example.test:6443"
	initConfiguration.CertificatesDir = filepath.Join(t.TempDir(), "pki")
	config := &Configuration{InitConfiguration: *initConfiguration}

	ca, err := GenerateCACertificatePrivateKeyPair(kubeadmconstants.CACertAndKeyBaseName, config)
	require.NoError(t, err)

	// Far from the process start time, which kubeadm would use.
	issuedAt := time.Now().Add(10 * 24 * time.Hour).Truncate(time.Second)

	for _, name := range []string{
		kubeadmconstants.AdminKubeConfigFileName,
		kubeadmconstants.SuperAdminKubeConfigFileName,
		kubeadmconstants.ControllerManagerKubeConfigFileName,
		kubeadmconstants.SchedulerKubeConfigFileName,
	} {
		t.Run(name, func(t *testing.T) {
			content, err := createKubeconfig(name, *ca, config, issuedAt)
			require.NoError(t, err)

			got, err := clientcmd.Load(content)
			require.NoError(t, err)

			// Same server, names and identity as the kubeconfig generated by kubeadm.
			want := kubeadmKubeconfig(t, name, *ca, config)
			require.Equal(t, want.CurrentContext, got.CurrentContext)
			require.Equal(t, want.Contexts, got.Contexts)
			require.Len(t, got.Clusters, 1)

			for clusterName, cluster := range want.Clusters {
				require.Equal(t, cluster.Server, got.Clusters[clusterName].Server)
				require.Equal(t, cluster.CertificateAuthorityData, got.Clusters[clusterName].CertificateAuthorityData)
			}

			require.Len(t, got.AuthInfos, 1)

			for user, authInfo := range want.AuthInfos {
				wantCert := parseCertificate(t, authInfo.ClientCertificateData)
				gotCert := parseCertificate(t, got.AuthInfos[user].ClientCertificateData)

				require.Equal(t, wantCert.Subject.String(), gotCert.Subject.String())
				require.Equal(t, wantCert.ExtKeyUsage, gotCert.ExtKeyUsage)
				require.True(t, gotCert.NotAfter.Equal(issuedAt.Add(initConfiguration.CertificateValidityPeriod.Duration)), "NotAfter: %s", gotCert.NotAfter)
			}
		})
	}
}

func TestCreateKubeconfigRejectsUnknownFile(t *testing.T) {
	_, err := CreateKubeconfig(kubeadmconstants.KubeletKubeConfigFileName, CertificatePrivateKeyPair{}, &Configuration{})
	require.Error(t, err)
}

func kubeadmKubeconfig(t *testing.T, name string, ca CertificatePrivateKeyPair, config *Configuration) *clientcmdapi.Config {
	t.Helper()

	directory := t.TempDir()
	require.NoError(t, buildCertificateDirectoryWithCA(ca, directory))

	initConfiguration := config.InitConfiguration
	initConfiguration.CertificatesDir = directory
	require.NoError(t, kubeconfig.CreateKubeConfigFile(name, directory, &initConfiguration))

	content, err := os.ReadFile(filepath.Join(directory, name))
	require.NoError(t, err)

	kc, err := clientcmd.Load(content)
	require.NoError(t, err)

	return kc
}

func parseCertificate(t *testing.T, data []byte) *x509.Certificate {
	t.Helper()

	certificates, err := certutil.ParseCertsPEM(data)
	require.NoError(t, err)
	require.Len(t, certificates, 1)

	return certificates[0]
}
